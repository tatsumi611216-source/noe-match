    dv = DataValidation(type="list", formula1=STATUS, allow_blank=True)
    ws.add_data_validation(dv)
    dv.add("N3:N%d" % last)
    add_status_cf(ws, "N3:N%d" % last)

    dv2 = DataValidation(type="whole", operator="between", formula1="1", formula2="5",
                         allow_blank=True, showErrorMessage=True)
    dv2.error = "1〜5の整数を入れてください"
    ws.add_data_validation(dv2)
    dv2.add("F3:G%d" % last)

    ws.conditional_formatting.add("I3:I%d" % last, CellIsRule(
        operator="equal", formula=['"最優先"'],
        fill=PatternFill("solid", fgColor="A93C27"),
        font=Font(name=FONT, bold=True, color="FFFFFF")))
    ws.conditional_formatting.add("I3:I%d" % last, CellIsRule(
        operator="equal", formula=['"高"'],
        fill=PatternFill("solid", fgColor="F0C9BE"), font=Font(name=FONT, color="A93C27")))
