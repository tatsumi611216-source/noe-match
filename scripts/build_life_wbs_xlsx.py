def head_font():
    return Font(name=FONT, size=10, bold=True, color="FFFFFF")


def body_font(bold=False, color=INK, size=10):
    return Font(name=FONT, size=size, bold=bold, color=color)


def style_header(ws, row, ncols, fill):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = fill
        cell.font = head_font()
        cell.alignment = Alignment(vertical="center", wrap_text=True)
        cell.border = BOX
    ws.row_dimensions[row].height = 34


def title_block(ws, text, sub, ncols):
    ws.cell(row=1, column=1, value=text).font = Font(
        name=FONT, size=14, bold=True, color=ACCENT
    )
    ws.cell(row=1, column=4, value=sub).font = Font(name=FONT, size=9, color="6B756E")
    ws.row_dimensions[1].height = 24


def set_widths(ws, widths):
    for col, w in widths.items():
        ws.column_dimensions[col].width = w


