def sheet_wbs(wb):
    ws = wb.create_sheet("②WBS")
    title_block(ws, "② WBS｜想定される論点まで分解したタスク一覧",
                "「論点」「選択肢・候補」「判断軸」の3列が、実際に迷う場所です", 15)

    heads = ["WBS-ID", "フェーズ", "中分類", "タスク", "論点・決めること",
             "選択肢・候補", "判断軸・注意点", "経過月", "目安時期",
             "区分", "担当", "費用目安", "先行", "状態", "メモ"]
    for i, h in enumerate(heads, start=1):
        ws.cell(row=2, column=i, value=h)
    style_header(ws, 2, len(heads), F_HEAD)

    counters = {}
    r = 3
    for (ph, mid, task, ronten, opts, axis, month, kind, owner, cost, dep) in T:
        counters[ph] = counters.get(ph, 0) + 1
        wid = "%s-%02d" % (ph, counters[ph])
        ws.cell(row=r, column=1, value=wid)
        ws.cell(row=r, column=2, value=ph)
        ws.cell(row=r, column=3, value=mid)
        ws.cell(row=r, column=4, value=task).font = body_font(bold=True)
        ws.cell(row=r, column=5, value=ronten)
        ws.cell(row=r, column=6, value=opts)
        ws.cell(row=r, column=7, value=axis)
        ws.cell(row=r, column=8, value=month)
        d = ws.cell(row=r, column=9, value="=EDATE(%s,H%d)" % (BASE, r))
        d.number_format = 'yyyy"/"m'
        ws.cell(row=r, column=10, value=kind)
        ws.cell(row=r, column=11, value=owner)
        ws.cell(row=r, column=12, value=cost)
        ws.cell(row=r, column=13, value=dep)
        ws.cell(row=r, column=14, value="未着手").fill = F_INPUT
        ws.cell(row=r, column=15, value="").fill = F_INPUT

        for c in range(1, len(heads) + 1):
            cell = ws.cell(row=r, column=c)
            if c != 4:
                cell.font = body_font()
            cell.alignment = Alignment(vertical="top", wrap_text=(c in (4, 5, 6, 7, 12)))
            cell.border = BOX
        for c in (1, 2, 8, 9, 10, 11, 13, 14):
            ws.cell(row=r, column=c).alignment = Alignment(horizontal="center", vertical="top")
        if r % 2 == 1:
            for c in range(1, len(heads) + 1):
                if c not in (14, 15):
                    ws.cell(row=r, column=c).fill = F_BAND
        ws.row_dimensions[r].height = 62
        r += 1

    last = r - 1
    set_widths(ws, {"A": 9, "B": 7, "C": 9, "D": 34, "E": 26, "F": 46, "G": 52,
                    "H": 7, "I": 10, "J": 7, "K": 12, "L": 15, "M": 9, "N": 9, "O": 20})

    dv = DataValidation(type="list", formula1=STATUS, allow_blank=True)
    ws.add_data_validation(dv)
    dv.add("N3:N%d" % last)
    add_status_cf(ws, "N3:N%d" % last)

    # 「法定」区分を赤字で目立たせる
    ws.conditional_formatting.add("J3:J%d" % last, CellIsRule(
        operator="equal", formula=['"法定"'],
        fill=PatternFill("solid", fgColor="F6E3DD"),
        font=Font(name=FONT, bold=True, color=CRIT)))

    ws.freeze_panes = "E3"
    ws.auto_filter.ref = "A2:O%d" % last
    ws.sheet_view.zoomScale = 85
    return ws, last


