def render(art):
    parts = []
    for tag, text in art["body"]:
        parts.append("<%s>%s</%s>" % (tag, text, tag))
    return "".join(parts)


def main():
    os.makedirs(OUT, exist_ok=True)
    for art in ARTICLES:
        html = render(art)
        plain = re.sub(r"<[^>]+>", "", html)
        n = len(re.sub(r"\s", "", plain))
        io.open(os.path.join(OUT, art["slug"] + ".html"), "w", encoding="utf-8").write(html)
        io.open(os.path.join(OUT, art["slug"] + ".json"), "w", encoding="utf-8").write(
            json.dumps({"title": art["title"], "tags": art["tags"],
                        "kw": art["kw"], "chars": n}, ensure_ascii=False, indent=1))
        print("%-16s %s字  %s" % (art["slug"], n, art["title"][:40]))
        if n < 1500:
            print("   ⚠ 短い。既存の公開記事は1,900〜2,200字")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
